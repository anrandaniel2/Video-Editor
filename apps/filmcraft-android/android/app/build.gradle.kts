// The Rust half of the app is built in :native (android/native): one library for both halves of the
// app, with its Kotlin bindings. This file keeps the app's own assets, version and packaging, and
// takes the library from there. The cargo workspace is the `filmcraft-android` crate
// (apps/filmcraft-android), which sits in the FilmCraft cargo workspace two folders up.
val cargoWorkspaceDir: File = rootDir.parentFile.parentFile.parentFile
val rustAbis: List<String> =
    providers.gradleProperty("filmcraft.abis").getOrElse("arm64-v8a,x86_64").split(',').map { it.trim() }.filter { it.isNotEmpty() }
val minApi = 29

// The app's version: gradle.properties' filmcraft.version, or the version tag's when the release
// workflow builds a release. The version code follows from it (0.0.1-beta → 101, 0.0.1-beta.2 →
// 102, 0.0.1 → 199, 0.1.0-beta → 10001), so a pre-release comes before its release and every
// release before the next version's pre-releases; times ten plus the ABI of a one-ABI build
// (armeabi-v7a 1, arm64-v8a 2, x86_64 3; 0 for several), so each APK of a release has its own code
// (F-Droid needs that).
val appVersion: String = providers.gradleProperty("filmcraft.version").get()
val appVersionCode: Int = run {
    val m = requireNotNull(Regex("""(\d+)\.(\d+)\.(\d+)(-[0-9A-Za-z-]+?(\.(\d+))?)?""").matchEntire(appVersion)) {
        "filmcraft.version $appVersion is not a version like 1.2.3, 1.2.3-beta or 1.2.3-beta.4"
    }
    val (major, minor, patch) = m.groupValues.subList(1, 4).map { it.toInt() }
    val pre = if (m.groupValues[4].isEmpty()) null else m.groupValues[6].toIntOrNull() ?: 1
    require(minor < 100 && patch < 100 && (pre ?: 1) in 1..98) {
        "filmcraft.version $appVersion: minor and patch must be under 100, and a pre-release's number 1 to 98"
    }
    val base = ((major * 100 + minor) * 100 + patch) * 100 + (pre ?: 99)
    providers.gradleProperty("filmcraft.versionCode").orNull?.let { listed ->
        require(listed.trim().toIntOrNull() == base) {
            "gradle.properties: filmcraft.versionCode=$listed, but version $appVersion's is $base (set both before tagging)"
        }
    }
    val abi = when (rustAbis.singleOrNull()) {
        "armeabi-v7a" -> 1
        "arm64-v8a" -> 2
        "x86_64" -> 3
        else -> 0
    }
    base * 10 + abi
}

// The release key, when the build is given one (the release workflow passes it from the repository's
// secrets). Without one a release build is signed with the debug key: it installs, but it can't
// update a published release; or, with -Pfilmcraft.unsigned=true (F-Droid's build), not signed at
// all, so the published APK's signature can be checked against it.
val releaseKeystore: String? = providers.environmentVariable("FILMCRAFT_KEYSTORE").orNull
val unsignedRelease: Boolean = providers.gradleProperty("filmcraft.unsigned").orNull == "true"

/**
 * Files from FilmCraft's `assets/` the app ships, copied at build time rather than duplicated:
 * its app icon, its UI font Inter (OFL) and the font's licence. [targets] maps each file name to
 * its path in the generated resource (or asset) folder.
 */
abstract class FilmcraftAssets : DefaultTask() {
    @get:InputFiles @get:PathSensitive(PathSensitivity.NAME_ONLY) abstract val files: ConfigurableFileCollection
    @get:Input abstract val targets: MapProperty<String, String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun copy() {
        val out = outputDir.get().asFile
        out.deleteRecursively()
        for (file in files) {
            val target = targets.get()[file.name] ?: continue
            file.copyTo(File(out, target), overwrite = true)
        }
    }
}

/**
 * The app's UI icons (Lucide, ISC: FilmCraft's assets/icons, each with an attribution sidecar)
 * as Compose path data, generated at build time rather than copied: `LucideIcons.Scissors` and
 * so on, one per SVG. Lucide draws with strokes only, from paths, circles, ellipses, rects, lines
 * and polylines, which become SVG path strings here.
 */
abstract class LucideIconsTask : DefaultTask() {
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE) abstract val iconsDir: DirectoryProperty
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val out = outputDir.get().asFile
        out.deleteRecursively()
        val pkg = File(out, "io/github/artcraftandroid/filmcraft/ui").apply { mkdirs() }
        val attr = Regex("""([\w-]+)="([^"]*)"""")
        val element = Regex("""<(path|circle|ellipse|rect|line|polyline|polygon)\b([^>]*)/?>""")
        fun n(v: Double) = if (v == Math.floor(v)) v.toLong().toString() else v.toString()
        val sb = StringBuilder()
        sb.appendLine("// Generated by app/build.gradle.kts (LucideIconsTask) from assets/icons: do not edit.")
        sb.appendLine("package io.github.artcraftandroid.filmcraft.ui\n")
        sb.appendLine("import androidx.compose.ui.graphics.vector.ImageVector\n")
        sb.appendLine("/** Lucide icons (ISC, Lucide Contributors; assets/icons/LICENSE-lucide.txt). */")
        sb.appendLine("object LucideIcons {")
        val files = iconsDir.get().asFile.listFiles { f -> f.extension == "svg" }.orEmpty().sortedBy { it.name }
        for (f in files) {
            val paths = mutableListOf<String>()
            for (m in element.findAll(f.readText())) {
                val a = attr.findAll(m.groupValues[2]).associate { it.groupValues[1] to it.groupValues[2] }
                fun d(k: String) = a[k]?.toDoubleOrNull() ?: 0.0
                when (m.groupValues[1]) {
                    "path" -> a["d"]?.let(paths::add)
                    "circle", "ellipse" -> {
                        val rx = if (m.groupValues[1] == "circle") d("r") else d("rx")
                        val ry = if (m.groupValues[1] == "circle") d("r") else d("ry")
                        val cx = d("cx"); val cy = d("cy")
                        paths += "M${n(cx - rx)} ${n(cy)}a${n(rx)} ${n(ry)} 0 1 0 ${n(2 * rx)} 0a${n(rx)} ${n(ry)} 0 1 0 ${n(-2 * rx)} 0"
                    }
                    "rect" -> {
                        val x = d("x"); val y = d("y"); val w = d("width"); val h = d("height")
                        val rx = minOf(a["rx"]?.toDoubleOrNull() ?: a["ry"]?.toDoubleOrNull() ?: 0.0, w / 2)
                        val ry = minOf(a["ry"]?.toDoubleOrNull() ?: rx, h / 2)
                        paths += if (rx <= 0.0) "M${n(x)} ${n(y)}h${n(w)}v${n(h)}h${n(-w)}Z" else
                            "M${n(x + rx)} ${n(y)}H${n(x + w - rx)}A${n(rx)} ${n(ry)} 0 0 1 ${n(x + w)} ${n(y + ry)}V${n(y + h - ry)}" +
                                "A${n(rx)} ${n(ry)} 0 0 1 ${n(x + w - rx)} ${n(y + h)}H${n(x + rx)}A${n(rx)} ${n(ry)} 0 0 1 ${n(x)} ${n(y + h - ry)}" +
                                "V${n(y + ry)}A${n(rx)} ${n(ry)} 0 0 1 ${n(x + rx)} ${n(y)}Z"
                    }
                    "line" -> paths += "M${n(d("x1"))} ${n(d("y1"))}L${n(d("x2"))} ${n(d("y2"))}"
                    "polyline", "polygon" -> {
                        val pts = (a["points"] ?: "").trim().split(Regex("[\\s,]+")).filter { it.isNotEmpty() }
                        if (pts.size >= 4) {
                            val s = StringBuilder("M${pts[0]} ${pts[1]}")
                            for (i in 2 until pts.size - 1 step 2) s.append("L${pts[i]} ${pts[i + 1]}")
                            if (m.groupValues[1] == "polygon") s.append("Z")
                            paths += s.toString()
                        }
                    }
                }
            }
            if (paths.isEmpty()) continue
            val id = f.nameWithoutExtension.split('-').joinToString("") { p -> p.replaceFirstChar { it.uppercase() } }
            val list = paths.joinToString(", ") { "\"" + it.replace("\"", "") + "\"" }
            sb.appendLine("    val $id: ImageVector by lazy { lucide(\"${f.nameWithoutExtension}\", $list) }")
        }
        sb.appendLine("}")
        File(pkg, "LucideIcons.kt").writeText(sb.toString())
    }
}

android {
    namespace = "io.github.artcraftandroid.filmcraft"
    compileSdk = 37

    // The photo editor's interface is PhotoCraft's own Compose UI, kept in third_party/photocraft
    // and compiled here rather than as its own module: it needs the Kotlin bindings this module
    // already generates from filmcraft-android, and a separate module would either duplicate that
    // generation or depend back on :app.
    //
    // It is the *same* UI as before — the studio, its panels, the classic editor — and it drives
    // this crate's engine through the same command ids. A separate module made sense when the Rust
    // library was separate; now that the engine is FilmCraft's own, one module is honest.
    sourceSets.getByName("main") {
        // `java` and `kotlin` both: with AGP's built-in Kotlin the Kotlin sources live in the
        // `kotlin` source set, and pointing only `java` at a directory of .kt files compiles
        // nothing (the references stay unresolved, which is exactly how this first failed).
        java.srcDir("../../../../third_party/photocraft/android/app/src/main/java")
        kotlin.srcDir("../../../../third_party/photocraft/android/app/src/main/java")
        assets.srcDir("../../../../third_party/photocraft/android/app/src/main/assets")
    }

    defaultConfig {
        applicationId = "io.github.artcraftandroid.filmcraft"
        minSdk = minApi
        targetSdk = 36
        versionCode = appVersionCode
        versionName = appVersion
        ndk { abiFilters.addAll(rustAbis) }
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = providers.environmentVariable("FILMCRAFT_KEYSTORE_PASSWORD").orNull
                keyAlias = providers.environmentVariable("FILMCRAFT_KEY_ALIAS").orNull
                keyPassword = providers.environmentVariable("FILMCRAFT_KEY_PASSWORD").orNull
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = if (unsignedRelease) null else signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
            // reproducible builds: no record of the checkout in the APK
            vcsInfo { include = false }
        }
    }
    // reproducible builds: no dependency metadata signing block (F-Droid's check rejects it)
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }

    // Size: the APK carries its native libraries compressed.
    //
    // Since AGP 3.6 an APK whose minSdk is 23 or more keeps `lib/**/*.so` uncompressed and page
    // aligned, and sets `android:extractNativeLibs="false"` so the loader maps them straight out of
    // the APK. That suits an app bundle, where the store compresses the download itself. This app is
    // not shipped that way: the file on the releases page and in F-Droid *is* the download, and it
    // carries one Rust library — `libfilmcraft_android.so`: the engine and ProCraft's drawing and 3D
    // half together, with wgpu and naga — which is most of its bytes. ARM64 code deflates to about
    // half its size: on 0.0.61-beta the signed APK is 40 MB, of which the library was 27 MB (two
    // libraries then: the GPU stack was in both), where the default packing — where it is stored,
    // not deflated — makes it about 70 MB. Nothing at runtime changes: the installer extracts
    // the libraries once, as every app did before Android 6, and the loader maps the extracted copies
    // exactly as it mapped the ones inside the APK. No feature goes, and no code runs slower.
    //
    // The price is paid on the device instead of in the download: the installed app then holds the
    // APK plus its extracted libraries. `useLegacyPackaging = false` (or this whole block away)
    // trades that back the other way: a bigger download, no extracted copy.
    packaging {
        jniLibs {
            useLegacyPackaging = true
        }

        // Compiler and debugger metadata nothing reads at runtime: Kotlin's per-module metadata
        // (used by the compiler, not the app) and the coroutines' debugger probes.
        resources {
            excludes += setOf(
                "META-INF/*.kotlin_module",
                "META-INF/*.version",
                "DebugProbesKt.bin",
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
    }
}

androidComponents {
    beforeVariants(selector().withBuildType("release")) { builder ->
        builder.hostTests.getValue(com.android.build.api.variant.HostTestBuilder.UNIT_TEST_TYPE).enable = true
    }
    onVariants { variant ->
        val name = variant.name.replaceFirstChar { it.uppercase() }
        val assetsDir = File(cargoWorkspaceDir, "assets")
        val res = tasks.register<FilmcraftAssets>("filmcraftResources$name") {
            // The fonts are ProCraft's to ship (`res/font`, one copy for the whole app): this module
            // has none of its own.
            val map = mapOf(
                "app-icon/hicolor/512x512/apps/ai.storyteller.filmcraft.png" to "drawable-nodpi/ic_launcher_tile.png",
            )
            files.from(map.keys.map { File(assetsDir, it) })
            targets.set(map.mapKeys { (k, _) -> k.substringAfterLast('/') })
        }
        val licences = tasks.register<FilmcraftAssets>("filmcraftLicences$name") {
            files.from(File(assetsDir, "fonts/OFL-Inter.txt"), File(assetsDir, "icons/LICENSE-lucide.txt"))
            targets.set(mapOf("OFL-Inter.txt" to "licences/OFL-Inter.txt", "LICENSE-lucide.txt" to "licences/LICENSE-lucide.txt"))
        }
        val icons = tasks.register<LucideIconsTask>("lucideIcons$name") {
            iconsDir.set(File(assetsDir, "icons"))
        }
        variant.sources.java?.addGeneratedSourceDirectory(icons, LucideIconsTask::outputDir)
        variant.sources.res?.addGeneratedSourceDirectory(res, FilmcraftAssets::outputDir)
        variant.sources.assets?.addGeneratedSourceDirectory(licences, FilmcraftAssets::outputDir)
    }
}

